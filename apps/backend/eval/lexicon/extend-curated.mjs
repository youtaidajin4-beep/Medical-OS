/**
 * curated-lexicon-v1.json に語を足す。既存（標準の辞書・追加語彙）にある語は足さない。
 *   node eval/lexicon/extend-curated.mjs
 * 書式: '名前~よみ'（英字略語は読みなし）。薬は '一般名|商品名,商品名'。
 */
import fs from 'node:fs';
const DIR = new URL('../../src/modules/medical-knowledge/data/', import.meta.url);
const base = JSON.parse(fs.readFileSync(new URL('medical_os_internal_medicine_knowledge_v2.json', DIR), 'utf8'));
const cur = JSON.parse(fs.readFileSync(new URL('curated-lexicon-v1.json', DIR), 'utf8'));
const have = new Set([...base.terms, ...cur.terms].map((t) => t.canonical_name));
const brands = new Map([...base.medication_brand_generic, ...cur.medication_brand_generic].map((b) => [b.brand_name, b.generic_name]));
const HIRA = /^[぀-ゟー・]+$/;
const lines = (s) => s.split('\n').map((l) => l.trim()).filter(Boolean);
let added = 0;
function add(src, category) {
  for (const line of lines(src)) {
    const [left, brandPart = ''] = line.split('|');
    const [name, reading] = left.split('~');
    if (reading && !HIRA.test(reading)) throw new Error(`読みが不正: ${line}`);
    if (!have.has(name)) {
      cur.terms.push({ canonical_name: name, category, priority: 'normal', ...(reading ? { reading } : {}) });
      have.add(name); added++;
    }
    for (const b of brandPart.split(',').map((x) => x.trim()).filter(Boolean)) {
      if (b !== name && !brands.has(b)) { cur.medication_brand_generic.push({ brand_name: b, generic_name: name }); brands.set(b, name); }
    }
  }
}

