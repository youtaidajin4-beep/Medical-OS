    out.append("1. Chromeで本番にログイン → 新規患者（架空の名前）→ 録音画面 → **マイクの設定で、持ち帰ったマイクが選ばれているか**を確認\n"
               "2. 録音開始 → 台本（または音声）→ 「診察を終了して要約」\n"
               "3. 画面に出た **S/O/A/P と右側の「要確認」** を、各台本の「見るところ」と照らす\n"
               "4. 書類の手順がある台本は、続けて書類を作る\n")
    for s in SCRIPTS:
        d, chars = timings.get(s["id"], (0, 0))
        out.append(f"\n---\n\n## {s['title']}（約{s['minutes']}分）\n")
        out.append(f"- 患者：{s['who']}\n- 音声ファイル：`{s['id']}.mp3`（{d / 60:.1f}分・発話{chars}字）\n- 見たいこと：{s['purpose']}\n")
        out.append("### 台本\n")
        for ln in s["lines"]:
            if ln[0] == P:
                out.append(f"> 〔{ln[2]}・{ln[1]}秒〕")
            else:
                out.append(f"**{ln[0]}**　{ln[1]}")
            out.append("")
        out.append("### SOAPに載ってほしいこと（拾えたか数える）\n")
        for name, _ in s["targets"]:
            out.append(f"- [ ] {name}")
        out.append("\n### 載ってはいけないこと（1つでもあれば不具合）\n")
        for name, _ in s["forbidden"]:
            out.append(f"- [ ] {name}")
        if s["doc_steps"]:
            out.append("\n### 書類\n")
            for i, st in enumerate(s["doc_steps"], 1):
                out.append(f"{i}. {st}")
        out.append("")
    out.append("\n---\n\n## 結果の貼り方\n")
    out.append("台本ごとに、①画面のS/O/A/Pをそのまま貼る（スクリーンショット可）、②拾えなかった項目、③載ってはいけないものが出たか、④書類の紙で気づいたこと。"
               "このファイルの的は `cases-realistic.json` にもなっていて、貼ってもらえば同じ物差しで数えられる。\n")
    with open(DOC, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote", DOC)


