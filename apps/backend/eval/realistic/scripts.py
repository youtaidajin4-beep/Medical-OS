def say_wav(text, voice, gain_db, path):
    aiff = path + ".aiff"
    subprocess.run(["say", "-v", voice, "-o", aiff, text], check=True)
    subprocess.run(
        [FFMPEG, "-y", "-loglevel", "error", "-i", aiff, "-ar", "16000", "-ac", "1",
         "-af", f"volume={gain_db}dB,apad=pad_dur={GAP_SEC}", path],
        check=True,
    )
    os.remove(aiff)


def silence_wav(sec, path):
    subprocess.run(
        [FFMPEG, "-y", "-loglevel", "error", "-f", "lavfi", "-i", "anullsrc=r=16000:cl=mono",
         "-t", str(sec), path],
        check=True,
    )


def duration_sec(path):
    info = subprocess.run([FFMPEG, "-i", path], capture_output=True, text=True).stderr
    m = re.search(r"Duration: (\d+):(\d+):(\d+\.?\d*)", info)
    h, mi, se = int(m.group(1)), int(m.group(2)), float(m.group(3))
    return h * 3600 + mi * 60 + se


def build_audio(s):
    os.makedirs(OUT_DIR, exist_ok=True)
    work = os.path.join(OUT_DIR, "_work_" + s["id"])
    os.makedirs(work, exist_ok=True)
    voices = dict(VOICES)
    voices["患者"] = s["patient_voice"]
    parts = []
    for i, ln in enumerate(s["lines"]):
        p = os.path.join(work, f"{i:03d}.wav")
        if ln[0] == P:
            silence_wav(ln[1], p)
        else:
            say_wav(ln[1], voices[ln[0]], GAIN_DB[ln[0]], p)
        parts.append(p)
    listing = os.path.join(work, "list.txt")
    with open(listing, "w", encoding="utf-8") as f:
        for p in parts:
            f.write(f"file '{p}'\n")
    out = os.path.join(OUT_DIR, s["id"] + ".mp3")
    subprocess.run(
        [FFMPEG, "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", listing,
         "-codec:a", "libmp3lame", "-b:a", "64k", out],
        check=True,
    )
    d = duration_sec(out)
    for p in parts + [listing]:
        os.remove(p)
    os.rmdir(work)
    chars = sum(len(ln[1]) for ln in s["lines"] if ln[0] != P)
    print(f"{s['id']}  {d / 60:.1f}分  発話{chars}字  {out}")
    return d, chars


